# Collect the LG V30 firmware the mainline drivers load and generate
# vendor/lge/joan. Nothing here is redistributable: extract from your own
# phone.
#
# usage: extract-firmware.sh <modem-dir> <vendor-firmware-dir>
#   <modem-dir>            contents of the "modem" partition's image/ folder
#                          (adb pull /vendor/firmware_mnt/image, or a
#                          loop-mounted modem.img)
#   <vendor-firmware-dir>  /vendor/firmware of LineageOS 22.2 or stock
#                          (adb pull /vendor/firmware)
#
set -euo pipefail

MODEM=$(realpath "$1") VFW=$(realpath "$2")
TOP=$(realpath "$(dirname "$0")/../../..")
OUT=$TOP/vendor/lge/joan
FW=$OUT/proprietary/vendor/firmware

rm -rf "$OUT/proprietary"
mkdir -p "$FW/qcom/msm8998/joan" "$FW/qcom/H930" "$FW/qcom/H932" "$FW/qca" \
	"$FW/ath10k/WCN3990/hw1.0"

# Remote processors: modem (+ MBA), ADSP, SLPI, Venus.
for img in mba.mbn modem.mdt modem.b?? adsp.mdt adsp.b?? slpi_v2.mdt \
	slpi_v2.b?? venus.mdt venus.b??; do
	for f in "$MODEM"/$img; do
		[ -e "$f" ] && cp "$f" "$FW/qcom/msm8998/joan/"
	done
done

# Files the modem reads over TFTP (/readonly/firmware/image/...).
# tqftpserv serves them from the directory of the modem firmware.
cp "$MODEM"/wlanmdsp.mbn "$FW/qcom/msm8998/joan/"
[ -d "$MODEM"/modem_pr ] && cp -r "$MODEM"/modem_pr "$FW/qcom/msm8998/joan/"

# Wi-Fi DSP, IPA, WLAN board data.
cp "$MODEM"/wlanmdsp.mbn "$FW/"
cp "$MODEM"/ipa_fws.* "$FW/"
cp "$MODEM"/bdwlan.bin "$FW/ath10k/WCN3990/hw1.0/board.bin"

# ath10k WCN3990 host firmware API file and the signed regulatory
# database: redistributable, taken from the host's linux-firmware and an
# upstream wireless-regdb checkout (override with LINUX_FIRMWARE/REGDB).
LINUX_FIRMWARE=${LINUX_FIRMWARE:-/usr/lib/firmware}
REGDB=${REGDB:-$HOME/android/firmware/wireless-regdb/src}
zstdcat -f "$LINUX_FIRMWARE"/ath10k/WCN3990/hw1.0/firmware-5.bin* \
	> "$FW/ath10k/WCN3990/hw1.0/firmware-5.bin"
cp "$REGDB"/regulatory.db "$REGDB"/regulatory.db.p7s "$FW/"

# Adreno 540: microcode is shared with A530, GPMU and the signed zap shader
# are A540 specific. H932 ships its own signed zap; releasetools installs
# the matching set (see releasetools/device_check.sh).
cp "$VFW"/a530_pm4.fw "$VFW"/a530_pfp.fw "$VFW"/a540_gpmu.fw2 "$FW/qcom/"
cp "$VFW"/H930/a540_zap.* "$FW/qcom/H930/"
cp "$VFW"/H932/a540_zap.* "$FW/qcom/H932/"
cp "$VFW"/H930/a540_zap.* "$FW/qcom/"

# Bluetooth (WCN3990)
cp "$VFW"/crbtfw21.tlv "$VFW"/crnv21.bin "$FW/qca/"

# Check the modem segment set is complete: every non-empty program header
# of modem.mdt must have its .bNN file with the matching size.
python3 - "$FW/qcom/msm8998/joan" <<'EOF'
import os, struct, sys
d = sys.argv[1]
for base in ('modem', 'adsp', 'slpi_v2', 'venus'):
    mdt = os.path.join(d, base + '.mdt')
    if not os.path.exists(mdt):
        sys.exit(f'missing {mdt}')
    b = open(mdt, 'rb').read()
    # Hexagon images are ELF32; handle ELF64 too.
    if b[4] == 1:
        phoff, = struct.unpack_from('<I', b, 0x1c)
        phentsize, phnum = struct.unpack_from('<HH', b, 0x2a)
        fs_fmt, fs_off = '<I', 0x10
    else:
        phoff, = struct.unpack_from('<Q', b, 0x20)
        phentsize, phnum = struct.unpack_from('<HH', b, 0x36)
        fs_fmt, fs_off = '<Q', 0x20
    for i in range(phnum):
        filesz, = struct.unpack_from(fs_fmt, b, phoff + i * phentsize + fs_off)
        seg = os.path.join(d, f'{base}.b{i:02d}')
        if not filesz:
            continue
        if not os.path.exists(seg):
            sys.exit(f'missing {seg}')
        if os.path.getsize(seg) != filesz:
            sys.exit(f'{seg}: size {os.path.getsize(seg)} != {filesz}')
    print(f'{base}: {phnum} segments ok')
EOF

# Makefiles
{
	echo '# Automatically generated by device/lge/joan/extract-firmware.sh'
	echo
	echo 'PRODUCT_COPY_FILES += \'
	(cd "$OUT/proprietary" && find vendor -type f | sort) | while read -r f; do
		echo "    vendor/lge/joan/proprietary/$f:\$(TARGET_COPY_OUT_VENDOR)/${f#vendor/} \\"
	done
	echo
} > "$OUT/joan-vendor.mk"
echo '# Automatically generated by device/lge/joan/extract-firmware.sh' > "$OUT/BoardConfigVendor.mk"
echo "$(grep -c proprietary "$OUT/joan-vendor.mk") firmware files -> $OUT"
