# Collect the Qualcomm RIL (qcrild) and data (netmgrd) userspace from the
# LineageOS 22.2 joan vendor image (Fairphone 3 blobs, already fixed up by
# its extract-files.py) into vendor/lge/joan/radio. Its QMI client library
# speaks AF_QIPCRTR, so it runs against the mainline modem stack as is.
#
# Only the Qualcomm libraries are taken: anything the build already
# provides (AOSP libraries, HIDL interfaces built from source) is left out
# and listed in device.mk instead.
#
# usage: extract-radio.py <lineage-22.2-vendor-root> <android-product-out>

import os
import shutil
import subprocess
import sys

VENDOR, OUT = (os.path.realpath(p) for p in sys.argv[1:3])
TOP = os.path.realpath(os.path.join(os.path.dirname(__file__), '../../..'))
DEST = os.path.join(TOP, 'vendor/lge/joan/radio')
READELF = os.path.join(
    TOP, 'prebuilts/clang/host/linux-x86/llvm-binutils-stable/llvm-readelf')
if not os.path.exists(READELF):
    READELF = shutil.which('llvm-readelf') or 'readelf'

ROOTS = ['bin/hw/qcrild', 'bin/netmgrd']
# Built from source (device.mk), so never copied even though LOS 22 had them.
FROM_SOURCE_PREFIXES = (
    'android.', 'libbase', 'libc++', 'libcutils', 'libutils', 'libhidl',
    'libbinder', 'libz.', 'libsqlite', 'libxml2', 'libprotobuf', 'libnetutils',
    'libhardware', 'server_configurable', 'libaconfig', 'liblog', 'libvndksupport',
    'libapexsupport', 'libandroid_net',
)
BIONIC = {'libc.so', 'libdl.so', 'libm.so'}
DATA = [
    'etc/data/dsi_config.xml',
    'etc/data/netmgr_config.xml',
]


def needed(path):
    out = subprocess.run([READELF, '-d', path], capture_output=True, text=True).stdout
    return [l.split('[', 1)[1].rstrip(']') for l in out.splitlines() if '(NEEDED)' in l]


def built_by_us(lib):
    if lib.startswith(FROM_SOURCE_PREFIXES):
        return True
    return any(os.path.exists(os.path.join(OUT, part, 'lib64', lib))
               for part in ('vendor', 'system', 'system_ext'))


files, seen, todo = set(ROOTS), set(), list(ROOTS)
while todo:
    for lib in needed(os.path.join(VENDOR, todo.pop())):
        if lib in seen or lib in BIONIC:
            continue
        seen.add(lib)
        if built_by_us(lib):
            continue
        rel = 'lib64/' + lib
        if not os.path.exists(os.path.join(VENDOR, rel)):
            sys.exit(f'{lib}: not in the 22.2 vendor image and not built here')
        files.add(rel)
        todo.append(rel)

for root, _, names in os.walk(os.path.join(VENDOR, 'radio')):
    for n in names:
        files.add(os.path.relpath(os.path.join(root, n), VENDOR))
files.update(DATA)

shutil.rmtree(DEST, ignore_errors=True)
for rel in sorted(files):
    dst = os.path.join(DEST, 'proprietary/vendor', rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(os.path.join(VENDOR, rel), dst)

with open(os.path.join(DEST, 'radio-vendor.mk'), 'w') as mk:
    mk.write('# Automatically generated by device/lge/joan/extract-radio.py\n\n')
    mk.write('PRODUCT_COPY_FILES += \\\n')
    for rel in sorted(files):
        mk.write(f'    vendor/lge/joan/radio/proprietary/vendor/{rel}:'
                 f'$(TARGET_COPY_OUT_VENDOR)/{rel} \\\n')
    mk.write('\n')
print(f'{len(files)} radio files -> {DEST}')
